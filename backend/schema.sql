create table if not exists public.products (
  id bigint generated by default as identity primary key,
  category text not null,
  title text not null check (char_length(title) between 1 and 120),
  condition text not null default 'Očuvano',
  price numeric(10,2) not null check (price >= 0),
  description text not null default '',
  image_url text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  items jsonb not null,
  total numeric(10,2) not null check (total >= 0),
  payment_method text not null,
  status text not null default 'pending' check (status in ('pending','confirmed','fulfilled','cancelled')),
  customer_name text,
  customer_contact text,
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;
alter table public.orders enable row level security;

-- Browser users can only read active products. All writes go through the
-- backend, which keeps the Supabase service-role key off the public website.
drop policy if exists "Public can read active products" on public.products;
create policy "Public can read active products"
  on public.products for select to anon, authenticated using (active = true);

-- There are intentionally no browser policies for orders. The backend checks
-- each order and writes using its private service-role key.

create index if not exists products_active_category_idx on public.products (active, category);
create index if not exists orders_created_at_idx on public.orders (created_at desc);
